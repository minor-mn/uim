// Embeds the highlight queries in lib/src/queries.g.dart.
// Run from the package root: dart run tool/gen_queries.dart
import 'dart:io';

/// Query files of each language, concatenated in this order. Later patterns
/// win, so a base language comes before the one extending it.
const queries = {
  'bash': ['tree-sitter-bash/queries/highlights.scm'],
  'c': ['tree-sitter-c/queries/highlights.scm'],
  'cpp': [
    'tree-sitter-c/queries/highlights.scm',
    'tree-sitter-cpp/queries/highlights.scm',
  ],
  'crystal': ['tree-sitter-crystal/queries/nvim/highlights.scm'],
  'css': ['tree-sitter-css/queries/highlights.scm'],
  'dart': ['tree-sitter-dart/queries/highlights.scm'],
  'dockerfile': ['tree-sitter-dockerfile/queries/highlights.scm'],
  'elixir': ['tree-sitter-elixir/queries/highlights.scm'],
  'erlang': ['tree-sitter-erlang/queries/highlights.scm'],
  'groovy': ['tree-sitter-groovy/queries/highlights.scm'],
  'hcl': ['tree-sitter-hcl/queries/nvim/hcl/highlights.scm'],
  'html': ['tree-sitter-html/queries/highlights.scm'],
  'ini': ['tree-sitter-ini/queries/highlights.scm'],
  'java': ['tree-sitter-java/queries/highlights.scm'],
  'javascript': [
    'tree-sitter-javascript/queries/highlights.scm',
    'tree-sitter-javascript/queries/highlights-jsx.scm',
    'tree-sitter-javascript/queries/highlights-params.scm',
  ],
  'json': ['tree-sitter-json/queries/highlights.scm'],
  'json5': ['tree-sitter-json5/queries/highlights.scm'],
  'kotlin': ['tree-sitter-kotlin/queries/highlights.scm'],
  'make': ['tree-sitter-make/queries/highlights.scm'],
  'nginx': ['tree-sitter-nginx/queries/highlights.scm'],
  'properties': ['tree-sitter-properties/queries/highlights.scm'],
  'ruby': ['tree-sitter-ruby/queries/highlights.scm'],
  'sshConfig': ['tree-sitter-ssh-config/queries/highlights.scm'],
  'swift': ['tree-sitter-swift/queries/highlights.scm'],
  'terraform': [
    'tree-sitter-hcl/queries/nvim/hcl/highlights.scm',
    'tree-sitter-hcl/queries/nvim/terraform/highlights.scm',
  ],
  'toml': ['tree-sitter-toml/queries/highlights.scm'],
  'tsx': [
    'tree-sitter-javascript/queries/highlights.scm',
    'tree-sitter-javascript/queries/highlights-jsx.scm',
    'tree-sitter-typescript/queries/highlights.scm',
  ],
  'typescript': [
    'tree-sitter-javascript/queries/highlights.scm',
    'tree-sitter-typescript/queries/highlights.scm',
  ],
  'xml': ['tree-sitter-xml/queries/xml/highlights.scm'],
  'yaml': ['tree-sitter-yaml/queries/highlights.scm'],
};

void main() {
  final out = StringBuffer(
    '// Generated by tool/gen_queries.dart. Do not edit.\n',
  );
  for (final MapEntry(key: name, value: files) in queries.entries) {
    final source = StringBuffer();
    for (final file in files) {
      final text = File('third_party/$file').readAsStringSync();
      if (text.contains("'''")) {
        throw StateError("$file contains ''', which breaks embedding");
      }
      source.write('; $file\n$text\n');
    }
    out.write("\nconst ${name}Highlights = r'''\n$source''';\n");
  }
  File('lib/src/queries.g.dart').writeAsStringSync(out.toString());
}
