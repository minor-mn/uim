# Writes the CP932 decode tables to lib/src/cp932.g.dart, using Python's cp932
# codec. Run from the package root: python3 tool/gen_cp932.py
#
# lib/encoding.dart builds the encode table from these by taking, for each
# character, the first byte sequence in byte order (double bytes first). This
# checks that the rule gives the same bytes as Python's encoder.

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = range(0x40, 0xFD)


def char(data):
    try:
        text = data.decode('cp932')
    except UnicodeDecodeError:
        return 0
    return ord(text) if len(text) == 1 else 0


single = [char(bytes([b])) if b not in LEADS else 0 for b in range(256)]
double = [char(bytes([lead, trail])) for lead in LEADS for trail in TRAILS]

encode = {}
for i, u in enumerate(double):
    if u and u not in encode:
        encode[u] = bytes([LEADS[i // len(TRAILS)], TRAILS[i % len(TRAILS)]])
for b, u in enumerate(single):
    if u and u not in encode:
        encode[u] = bytes([b])
mismatch = [hex(u) for u, data in encode.items() if chr(u).encode('cp932') != data]
assert not mismatch, mismatch


def dart_list(values):
    lines = []
    for i in range(0, len(values), 16):
        lines.append('  ' + ', '.join(str(v) for v in values[i:i + 16]) + ',')
    return '\n'.join(lines)


with open('lib/src/cp932.g.dart', 'w') as out:
    out.write('// Generated by tool/gen_cp932.py from Python\'s cp932 codec. Do not edit.\n\n')
    out.write('/// Code point of each single byte; 0 if it is a lead byte or unused\n')
    out.write('/// (byte 0 is U+0000 itself).\n')
    out.write('const cp932Single = <int>[\n%s\n];\n\n' % dart_list(single))
    out.write('/// Code point of each double byte: lead 0x81-0x9F then 0xE0-0xFC, each\n')
    out.write('/// with trail 0x40-0xFC; 0 if unused.\n')
    out.write('const cp932Double = <int>[\n%s\n];\n' % dart_list(double))

print('single: %d, double: %d mapped, encode: %d' % (
    sum(1 for u in single if u), sum(1 for u in double if u), len(encode)))
